// #131: the pure part of "Bynk: Generate TypeScript Client". The command runs
// `bynk client`, which owns the module (types, codecs, routes); the extension
// only picks where it goes and says what happened, including the routes the
// client could not represent.

import { parseUnitHeader } from "./projectModel";

export type ClientLayout = "file" | "dir";

export interface ClientOptions {
  root: string;
  /** Where to write. Omitted when `[build.client]` names it: the CLI then
   *  takes `out`, `layout` and `service` from `bynk.toml`. */
  out?: string;
  layout?: ClientLayout;
  services?: readonly string[];
}

/** `bynk client <root> [--out P] [--layout dir] [--service N]...`. With only a
 *  root, the CLI reads everything else from `[build.client]`. */
export function clientArgs(opts: ClientOptions): string[] {
  const args = ["client", opts.root];
  if (opts.out !== undefined) args.push("--out", opts.out);
  if (opts.layout === "dir") args.push("--layout", "dir");
  for (const s of opts.services ?? []) args.push("--service", s);
  return args;
}

/** The names of the `from http` services a Bynk source declares. */
export function httpServiceNames(text: string): string[] {
  const names: string[] = [];
  for (const m of text.matchAll(/^[ \t]*service\s+([A-Za-z_]\w*)\s+from\s+http\b/gm)) names.push(m[1]);
  return names;
}

/** The `from http` services across a project's sources, sorted. `--service`
 *  takes `Name` or `unit.Name`, so a name two units both declare is offered as
 *  `unit.Name` (when a file has no recognisable unit header it stays bare). */
export function httpServiceChoices(sources: readonly string[]): string[] {
  const found: { unit?: string; name: string }[] = [];
  for (const text of sources) {
    const names = httpServiceNames(text);
    if (names.length === 0) continue;
    const unit = parseUnitHeader(text)?.name;
    for (const name of names) found.push({ unit, name });
  }
  const count = new Map<string, number>();
  for (const f of found) count.set(f.name, (count.get(f.name) ?? 0) + 1);
  const out = new Set(found.map((f) => ((count.get(f.name) ?? 0) > 1 && f.unit ? `${f.unit}.${f.name}` : f.name)));
  return [...out].sort();
}

/** The routes the CLI left out: its `bynk: skipped <route>: <why>` lines. */
export function skippedRoutes(stderr: string): string[] {
  const out: string[] = [];
  for (const line of stderr.split(/\r?\n/)) {
    const m = /^bynk: skipped (.+)$/.exec(line.trim());
    if (m) out.push(m[1]);
  }
  return out;
}

/** What a failed run means to the person who ran it. */
export function clientFailure(stderr: string): string {
  if (/unrecogni[sz]ed subcommand|unknown subcommand/i.test(stderr)) {
    return "This Bynk toolchain has no `bynk client` command (it needs v0.607 or later). Update it, or run Bynk: Doctor.";
  }
  if (/refusing to overwrite/i.test(stderr)) {
    return (
      "`bynk client` will not overwrite a file it did not write (its first line is not `// @generated by `bynk client``). " +
      "Choose another location, or move that file out of the way.\n" +
      stderr.trim()
    );
  }
  if (/the project has no `from http` service/i.test(stderr)) {
    return "This project has no `from http` service, so there is no client to generate.";
  }
  if (/no `from http` service `[^`]*`/i.test(stderr)) {
    return `No such service.\n${stderr.trim()}`;
  }
  if (/no route of the selected services/i.test(stderr)) {
    return `Every route of the selected services is one the client cannot represent yet.\n${stderr.trim()}`;
  }
  // "`GET /a` and `GET /b` of service `api` both make the function `getA`; the
  // client cannot name them apart".
  if (/both make the function|cannot name them apart/.test(stderr)) {
    return `Two routes would share a client function name, so nothing was written.\n${stderr.trim()}`;
  }
  const detail = stderr.trim();
  return detail === ""
    ? "`bynk client` failed without a message."
    : `\`bynk client\` failed (the project must check clean):\n${detail}`;
}

export type ClientOutcome =
  | { kind: "cancelled" }
  | { kind: "failed"; message: string }
  | { kind: "written"; skipped: string[] };

/** Map a finished run to its outcome. A cancelled run is not a failure. */
export function clientOutcome(
  run: { code: number | null; stderr: string } | { error: unknown },
  cancelled: boolean,
): ClientOutcome {
  if (cancelled) return { kind: "cancelled" };
  if ("error" in run) {
    const e = run.error;
    return { kind: "failed", message: e instanceof Error ? e.message : String(e) };
  }
  if (run.code !== 0) return { kind: "failed", message: clientFailure(run.stderr) };
  return { kind: "written", skipped: skippedRoutes(run.stderr) };
}
